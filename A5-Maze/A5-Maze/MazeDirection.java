/**
 *  MazeDirection represents one of the four cardinal directions, or none.
 *
 *  @author  Nicholas R. Howe
 *  @version CSC 112, 20 March 2006
 */
public enum MazeDirection {
  /** North direction. */
  NORTH,
  /** South direction. */
  SOUTH,
  /** East direction. */
  EAST,
  /** West direction. */
  WEST,
  /** No direction. */
  NONE;
}
